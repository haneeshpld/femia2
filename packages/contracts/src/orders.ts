import { z } from 'zod';
import { Email, Id, Paise, Phone, Pincode } from './common.ts';

export const OrderStatus = z.enum(['pending_payment', 'new', 'confirmed', 'packed', 'shipped', 'delivered', 'cancelled']);
export type OrderStatus = z.infer<typeof OrderStatus>;

export const PaymentMethod = z.enum(['upi', 'gateway', 'cod', 'whatsapp']);
export type PaymentMethod = z.infer<typeof PaymentMethod>;

export const PaymentStatus = z.enum(['unpaid', 'paid', 'failed', 'cod', 'refunded']);
export type PaymentStatus = z.infer<typeof PaymentStatus>;

export const OrderChannel = z.enum(['web', 'whatsapp', 'phone', 'shop']);
export type OrderChannel = z.infer<typeof OrderChannel>;

/** Allowed manual transitions. pending_payment → new happens via payment confirmation only. */
/** Statuses a shopper can still cancel from (before packing). */
export const CUSTOMER_CANCELLABLE: OrderStatus[] = ['pending_payment', 'new', 'confirmed'];

export const ORDER_TRANSITIONS: Record<OrderStatus, OrderStatus[]> = {
  pending_payment: ['cancelled'],
  new: ['confirmed', 'cancelled'],
  confirmed: ['packed', 'cancelled'],
  packed: ['shipped', 'cancelled'],
  shipped: ['delivered'],
  delivered: [],
  cancelled: [],
};
export const canTransition = (from: OrderStatus, to: OrderStatus) => ORDER_TRANSITIONS[from].includes(to);

export const Address = z.object({
  line1: z.string().trim().min(3, 'Enter your house / street').max(120),
  line2: z.string().trim().max(120).default(''),
  city: z.string().trim().min(2, 'Enter your town or city').max(60),
  pincode: Pincode,
  state: z.string().default('KL'),
  landmark: z.string().trim().max(80).default(''),
});
export type Address = z.infer<typeof Address>;

export const CartLineInput = z.object({ variantId: Id, qty: z.number().int().min(1).max(10) });
export const CartQuoteRequest = z.object({
  lines: z.array(CartLineInput).max(30),
  coupon: z.string().trim().toUpperCase().max(20).nullable().optional(),
  /** lets the server check first-order and per-customer coupon rules before checkout */
  phone: z.string().max(20).nullable().optional(),
});
export type CartQuoteRequest = z.infer<typeof CartQuoteRequest>;

export const CheckoutRequest = z.object({
  lines: z.array(CartLineInput).min(1).max(30),
  customer: z.object({
    name: z.string().trim().min(2, 'Enter your name').max(80),
    phone: Phone,
    email: Email,
  }),
  address: Address,
  paymentMethod: PaymentMethod,
  /** Online payments (Razorpay): open straight on UPI, or on cards / netbanking / wallets. */
  payWith: z.enum(['upi', 'other']).nullable().default(null),
  newsletter: z.boolean().default(false),
  /** signed-in shoppers: keep this address in their account */
  saveAddress: z.boolean().default(false),
  coupon: z.string().trim().toUpperCase().max(20).nullable().default(null),
  /** idempotency key generated by the browser per checkout attempt */
  clientRef: z.string().min(8).max(64),
});
export type CheckoutRequest = z.input<typeof CheckoutRequest>;

export const OrderItem = z.object({
  variantId: Id, productId: Id, slug: z.string(), title: z.string(), optionLabel: z.string(), sku: z.string(),
  imageUrl: z.string().nullable(), unitPrice: Paise, qty: z.number().int(), lineTotal: Paise,
});
export type OrderItem = z.infer<typeof OrderItem>;

export const OrderEvent = z.object({ status: z.string(), note: z.string().nullable(), at: z.string() });

/** What the customer may see (confirmation + tracking pages). */
export const PublicOrder = z.object({
  number: z.string(),
  status: OrderStatus,
  paymentMethod: PaymentMethod,
  paymentStatus: PaymentStatus,
  items: z.array(OrderItem),
  subtotal: Paise,
  discount: Paise.default(0),
  discounts: z.array(z.object({ label: z.string(), code: z.string().nullable(), amount: Paise })).default([]),
  shipping: Paise,
  total: Paise,
  customerName: z.string(),
  city: z.string(),
  pincode: z.string(),
  courier: z.string().nullable(),
  trackingNumber: z.string().nullable(),
  trackingUrl: z.string().nullable(),
  timeline: z.array(OrderEvent),
  createdAt: z.string(),
  /** What the shopper paid and how (the gateway's payment id is their reference). */
  payment: z.object({
    method: PaymentMethod, status: PaymentStatus, amount: Paise, provider: z.string().nullable(),
    reference: z.string().nullable(), gatewayOrderId: z.string().nullable(), paidAt: z.string().nullable(),
    /** what was used inside the gateway: upi, card, netbanking, wallet, emi, paylater */
    instrument: z.string().nullable().default(null),
  }).nullable().default(null),
  refunds: z.array(z.object({
    amount: Paise, status: z.enum(['pending', 'processed', 'failed', 'to_send', 'sent']), reference: z.string().nullable(),
    toOriginal: z.boolean(), createdAt: z.string(), processedAt: z.string().nullable(),
  })).default([]),
  /** Shoppers can cancel until the order is packed. */
  canCancel: z.boolean().default(false),
  cancelledBy: z.string().nullable().default(null),
});
export type PublicOrder = z.infer<typeof PublicOrder>;

export const CANCEL_REASONS = ['Ordered by mistake', 'Want a different size or colour', 'Found it cheaper elsewhere', 'Delivery is taking too long', 'Changed my mind', 'Other'] as const;
export const CustomerCancel = z.object({
  token: z.string().min(8).max(100),
  reason: z.enum(CANCEL_REASONS),
  note: z.string().trim().max(300).default(''),
});
export const RefundInput = z.object({ amount: Paise.refine((n) => n > 0, 'Enter an amount'), reason: z.string().trim().min(2, 'Add a reason').max(200) });
export const ManualRefundSent = z.object({ reference: z.string().trim().min(3, 'Add the UPI reference (UTR) or a note').max(80) });

/** Response to POST /orders: tells the browser what to do next. */
export const CheckoutResult = z.object({
  order: PublicOrder,
  accessToken: z.string(),
  next: z.discriminatedUnion('type', [
    z.object({ type: z.literal('confirmation') }),
    z.object({ type: z.literal('upi'), upiUri: z.string(), payee: z.string(), amount: Paise, holdUntil: z.string() }),
    z.object({ type: z.literal('whatsapp'), url: z.string() }),
    z.object({ type: z.literal('gateway'), provider: z.string(), payload: z.record(z.string(), z.unknown()), holdUntil: z.string() }),
  ]),
});
export type CheckoutResult = z.infer<typeof CheckoutResult>;

export const TrackRequest = z.object({ number: z.string().trim().toUpperCase().min(4).max(20), phone: Phone });
export type TrackRequest = z.input<typeof TrackRequest>;

/** How a gateway payment was made, in words ("UPI", "Card"…). */
export const instrumentLabel = (i: string | null | undefined) =>
  i ? ({ upi: 'UPI', card: 'Card', netbanking: 'Netbanking', wallet: 'Wallet', emi: 'EMI', paylater: 'Pay later', cardless_emi: 'Cardless EMI' } as Record<string, string>)[i] ?? i : null;
